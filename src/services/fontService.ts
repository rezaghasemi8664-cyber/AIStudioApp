import type { AppFont } from '../types';
import { get, post, put, del } from './apiClient';

type FontType = 'persian' | 'latin';

const DEFAULT_PERSIAN_FONT = 'B Nazanin';
const DEFAULT_LATIN_FONT = 'Roboto';

interface FontsPayload {
  fonts: AppFont[];
  selected: {
    persian: string;
    latin: string;
  };
}

function normalizeFontsPayload(data: any): FontsPayload {
  const fonts: AppFont[] = Array.isArray(data?.fonts) ? data.fonts : [];
  const selected = {
    persian: data?.selected?.persian || DEFAULT_PERSIAN_FONT,
    latin: data?.selected?.latin || DEFAULT_LATIN_FONT,
  };

  return { fonts, selected };
}

function injectFontFace(name: string, url?: string): void {
  if (!url) return; // system font

  const styleId = `font-face-${name.replace(/\s+/g, '-').toLowerCase()}`;
  if (document.getElementById(styleId)) return;

  const style = document.createElement('style');
  style.id = styleId;
  style.textContent = `
    @font-face {
      font-family: '${name}';
      src: url('${url}') format('woff2');
      font-weight: normal;
      font-display: swap;
    }
  `;
  document.head.appendChild(style);
}

function applyCssVars(selected: { persian: string; latin: string }): void {
  document.documentElement.style.setProperty('--font-sans-fa', selected.persian || DEFAULT_PERSIAN_FONT);
  document.documentElement.style.setProperty('--font-sans-en', selected.latin || DEFAULT_LATIN_FONT);
}

/**
 * ???? ??? ???????:
 * ???? ???? ?????? ?? ?? ?????? ??????? ? ??? UI ????? ??????.
 */
export const initializeFonts = async (): Promise<void> => {
  const res = await get<any>('/ui-config/fonts/active');
  if (!res.success) throw new Error(res.message || '?????? ???? ???? ?????? ???');

  const payload = normalizeFontsPayload(res.data);
  payload.fonts.forEach((f) => injectFontFace(f.name, f.url));
  applyCssVars(payload.selected);
};

/**
 * ????? ????? (?????? ???? ???? ???????)
 */
export const getFonts = async (): Promise<AppFont[]> => {
  const res = await get<any>('/ui-config/fonts');
  if (!res.success) throw new Error(res.message || '?????? ???? ??????? ?????? ???');

  const payload = normalizeFontsPayload(res.data);
  payload.fonts.forEach((f) => injectFontFace(f.name, f.url));
  return payload.fonts;
};

/**
 * ????? ?????
 */
export const addFont = async (name: string, type: FontType, url: string): Promise<AppFont[]> => {
  const res = await post<any>('/ui-config/fonts', { name, type, url });
  if (!res.success) throw new Error(res.message || '?????? ???? ?????? ???');

  // ??? ?????? ?? ???? ?? ????????
  const payload = normalizeFontsPayload(res.data);
  if (payload.fonts.length > 0) {
    payload.fonts.forEach((f) => injectFontFace(f.name, f.url));
    return payload.fonts;
  }

  // fallback
  return await getFonts();
};

