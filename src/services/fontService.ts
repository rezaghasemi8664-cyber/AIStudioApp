/**
 * ????? ?????
 */
export const setSelectedFont = async (type: FontType, fontName: string): Promise<void> => {
  const res = await put<any>('/ui-config/fonts/selected', { type, fontName });
  if (!res.success) throw new Error(res.message || '????? ???? ??????? ?????? ???');

  // ????? ???? ?? UI ???? ?????
  if (type === 'persian') {
    document.documentElement.style.setProperty('--font-sans-fa', fontName);
  } else {
    document.documentElement.style.setProperty('--font-sans-en', fontName);
  }
};

