type ClaimResponse = {
  allowed: boolean;
  message?: string;
  remainingMinutes?: number;
  remainingCount24h?: number;
};

type ApiEnvelope<T> = {
  success?: boolean;
  data?: T;
  message?: string;
};

const unwrapApi = <T>(payload: ApiEnvelope<T> | T): T => {
  if (payload && typeof payload === 'object' && 'success' in (payload as ApiEnvelope<T>)) {
    const wrapped = payload as ApiEnvelope<T>;

    if (wrapped.success === false) {
      throw new Error(wrapped.message || '??????? ?????? ???.');
    }

    return (wrapped.data as T) ?? ({} as T);
  }

  return payload as T;
};

